const ACH_LOCK = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><rect x="5" y="10.5" width="14" height="10" rx="2.5"/><path d="M8.5 10.5V7.8a3.5 3.5 0 0 1 7 0v2.7"/></svg>';

// Мелкий значок теряет тонкие линии, крупный — наоборот, выглядит жирным.
function achStroke(size) {
  if (!size) return null;
  if (size <= 36) return 2.2;
  if (size <= 48) return 2;
  if (size >= 80) return 1.6;
  return 1.8;
}

// Номер ступени (серия «15», домашка «25») рисуется не поверх иконки,
// а отдельным ярлыком у нижнего края — как ленточка у медали.
// На мелком значке ярлык не помещается и прячется: номер остаётся
// в подписи карточки.
function achRankHtml(a) {
  if (a.need == null || !a.group || a.group === 'cert' || a.group === 'anti') return '';
  return '<span class="ach-rank">' + a.need + '</span>';
}

// Значок: круглая медаль. locked — серый, полупрозрачный, с замочком.
// size (px) необязателен: без него размер берётся из CSS (--ach-size).
function achBadgeHtml(code, locked, size) {
  const a = ACH_BY_CODE[code];
  if (!a) return '';
  const sw = achStroke(size);
  const style = size ? ' style="--ach-size:' + size + 'px;--ach-sw:' + sw + '"' : '';
  const small = size && size <= 36 ? ' is-small' : '';
  return '<span class="ach-badge tier-' + a.tier + (locked ? ' is-locked' : '') + small + '"' + style + '>' +
    '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    (ACH_ICONS[a.icon] || '') + '</svg>' +
    (locked ? '<span class="ach-lock">' + ACH_LOCK + '</span>' : achRankHtml(a)) +
    '</span>';
}
